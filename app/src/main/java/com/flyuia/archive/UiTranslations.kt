internal fun uiText(source: String): String {
    val code = activeLanguageCode.substringBefore('-').lowercase()
    val table = when (code) {
        "uk" -> ukrainianUi
        "bg" -> bulgarianUi
        "en" -> englishUi
        else -> emptyMap()
    }
    return table[source] ?: extendedUiText(source, code) ?: if (code !in setOf("ru", "uk", "bg", "en")) englishUi[source] ?: source else source
}
